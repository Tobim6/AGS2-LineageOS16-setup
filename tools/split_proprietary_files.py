#!/usr/bin/env python3
"""Splits device_huawei_AGS2/proprietary-files.txt into:
  - proprietary-files-automk.txt: vendor/product entries, with the
    "leftover" (not bin/lib/lib64/app/priv-app/framework/etc/sbin)
    vendor-sourced files explicitly prefixed "vendor/" so extract_utils'
    write_product_copy_files (treble-compat mode) routes them to
    /vendor instead of defaulting to /system. build.prop/default.prop
    are dropped (generated by the build, not blobs to copy verbatim).
  - odm-files.txt: bare (odm/ prefix stripped) relative paths, handled
    by hand-written PRODUCT_COPY_FILES into $(TARGET_COPY_OUT_ODM)
    since this extract_utils.sh version has no native odm support.
"""
import os
import subprocess
import sys

PROPRIETARY_ROOT = "/home/tobim6/AGS2_LOS16/vendor_huawei_AGS2/proprietary"


def is_fake_xml(partition, rel_path):
    """Android's build-time copy rule for any .xml-suffixed file runs
    xmllint over it first, regardless of whether it lands via
    PRODUCT_COPY_FILES or PRODUCT_PACKAGES -- a hard copy failure if it
    doesn't parse. A handful of Huawei "cust" policy files and a
    native-package registry ship with a .xml extension but are
    actually binary/encrypted blobs (confirmed with `file` + `xxd` --
    e.g. product/etc/xml/iaware_config_cust.xml opens with raw
    high-entropy bytes, not '<'). Checked with xmllint itself rather
    than hardcoding names, so any future re-extraction catches this
    automatically."""
    if not rel_path.endswith(".xml"):
        return False
    path = os.path.join(PROPRIETARY_ROOT, partition, rel_path)
    if not os.path.isfile(path):
        return False
    result = subprocess.run(["xmllint", "--noout", path],
                             stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    return result.returncode != 0


def is_broken_symlink(partition, rel_path):
    """Huawei's own extracted tree has ~1170 symlinks (all under odm/, a
    few under vendor/preavs and pointing at /system/lib) that use
    absolute on-device mount paths (/odm/..., /vendor/..., /system/...)
    as their target -- valid at runtime once partitions are mounted at
    their real mountpoints, but unresolvable in our offline extraction
    tree, so stat()-based build tooling (kati/ninja) sees them as
    missing. Every case checked has its real content already packaged
    under a different, non-symlink path (e.g. per-model
    hw_odm/AGS2-*/ncfg/*.ato symlinks all point back to the canonical
    hw_odm/ncfg/*.ato, which is a real file and separately listed) --
    so dropping the symlink entry loses nothing."""
    path = os.path.join(PROPRIETARY_ROOT, partition, rel_path)
    return os.path.islink(path) and not os.path.exists(path)


CATEGORY_PREFIXES = ("bin/", "lib/", "lib64/", "app/", "priv-app/",
                     "framework/", "etc/", "sbin/")
APP_CATEGORY_PREFIXES = ("app/", "priv-app/", "framework/")
DROP_BASENAMES = {"build.prop", "default.prop", "NOTICE.txt", "NOTICE.xml",
                   "NOTICE.xml.gz", "NOTICE.html", "NOTICE.html.gz",
                   "noticeFile"}


def needs_build_prebuilt_but_unsupported(rel_path):
    """.apk/.jar can never go through plain PRODUCT_COPY_FILES (hard
    build/make/core/Makefile error: 'use BUILD_PREBUILT instead!'), and
    write_product_packages only recognizes bare app/, priv-app/,
    framework/ as category prefixes -- not overlay/, region_comm/.../
    app/NAME/, jar/NAME/, hw_oem/MODEL/overlay/ etc, which is where most
    of these actually live in this vendor tree. No way to package them
    via this tool; drop entirely rather than hit a hard build error."""
    if not rel_path.endswith((".apk", ".jar")):
        return False
    return not rel_path.startswith(APP_CATEGORY_PREFIXES)

# Module names that collide with an existing AOSP/LOS module of the same
# name somewhere else in the tree (found by diffing our full module list
# against every LOCAL_MODULE/Android.bp "name" in the synced source tree).
# ckati's duplicate-module check fires at Android.mk *parse* time
# regardless of whether the module is actually in PRODUCT_PACKAGES, so
# there is no way to keep these as named MODULES without also disabling
# AOSP's own definition. Most are core system infra (sepolicy contexts,
# toybox/init/recovery/shell, fs_config, vndservice) that should come
# from the LOS build anyway, not a stock blob.
#
# libril and rild were in this list too until it turned out AOSP
# anticipates exactly this collision and provides an opt-out:
# BOARD_PROVIDES_LIBRIL/ENABLE_VENDOR_RIL_SERVICE (set in
# device/huawei/AGS2/BoardConfig.mk) suppress hardware/ril/{libril,rild}'s
# own module definitions, so our real Balong-modem blobs can be the sole
# "libril"/"rild" module instead of AOSP's generic reference versions
# (confirmed different size/hash -- the generic one doesn't talk to this
# modem). libreference-ril/librilutils have no such guard and are
# unconditionally pulled into every product's PRODUCT_PACKAGES by
# build/target/product/base.mk, so those two stay dropped for real (no
# functional loss believed -- librilutils is generic IPC glue, and
# libreference-ril's generic version is simulator-oriented and inert
# once Huawei's own libril/rild are doing the real work).
with open("/home/tobim6/AGS2_LOS16/work/colliding_names.txt") as _f:
    COLLIDING_MODULE_NAMES = {l.strip() for l in _f if l.strip()}

# Names that collide at ckati parse time (same as above) but whose AOSP
# definition is never actually *selected* for our product -- neither
# hi6250-common nor device/huawei/AGS2 reference these modules anywhere,
# so nothing pulls AOSP's version into PRODUCT_PACKAGES or in as a
# transitive dependency. Safe to fall back to a plain copy-file (ckati
# never complains about a copy-file sharing a name with an unselected
# module, and there's no competing ninja install rule for the same
# output path since AOSP's module is never installed) instead of
# dropping outright -- recovers real functionality (e.g. the real
# Broadcom WiFi HAL) rather than losing it.
with open("/home/tobim6/AGS2_LOS16/work/demote_names.txt") as _f:
    DEMOTE_MODULE_NAMES = {l.strip() for l in _f if l.strip()}


def is_unbuildable_hap(rel_path):
    """.hap (HarmonyOS "Feature Ability" package) files sometimes sit
    directly alongside a device's real .apk in an app/ dir (bundled
    HarmonyOS-hybrid widgets/FA-cards) -- if they land under one of
    APP_CATEGORY_PREFIXES, write_product_packages's app/ category
    match treats them as a normal APK module and runs them through
    signapk, which throws ("No AndroidManifest.xml in APK") since a
    .hap is a different package format entirely. Not an Android app,
    can't be installed as one -- drop; the device's real functionality
    is covered by its separate genuine .apk (e.g. HwHealthHm ships
    both HwHealthHm_signed_entry.apk -- which we do package -- and
    these .hap FA-card extras, which we don't)."""
    return rel_path.endswith(".hap") and rel_path.startswith(APP_CATEGORY_PREFIXES)


def collides(rel_path):
    """True if this name collides with an existing AOSP/LOS module
    anywhere in the tree, regardless of whether the eventual handling
    is to drop it or demote it to a copy-file -- demotable_collision()
    decides which, but the collision check itself must see both sets,
    or a name moved from colliding_names.txt to demote_names.txt would
    stop being recognized as colliding at all and fall through to
    (broken) module treatment."""
    basename = rel_path.rsplit("/", 1)[-1]
    stem = basename.rsplit(".", 1)[0] if "." in basename else basename
    names = COLLIDING_MODULE_NAMES | DEMOTE_MODULE_NAMES
    return basename in names or stem in names


def demotable_collision(rel_path):
    basename = rel_path.rsplit("/", 1)[-1]
    stem = basename.rsplit(".", 1)[0] if "." in basename else basename
    return basename in DEMOTE_MODULE_NAMES or stem in DEMOTE_MODULE_NAMES


def is_non_so_lib(rel_path):
    """A SHARED_LIBRARIES-class module (lib/lib64 category) is always
    stripped at build time, which hard-fails ('File format not
    recognized') on anything that isn't a real ELF .so -- e.g. a
    stray product/lib64/readme.txt bundled alongside a vendor SDK's
    actual libraries. bin/sbin EXECUTABLES aren't stripped the same
    way (toybox tools and signed .sec TA blobs there build fine), so
    this only applies to lib/lib64."""
    parts = rel_path.split("/")
    return len(parts) >= 2 and parts[0] in ("lib", "lib64") and not rel_path.endswith(".so")


def is_hal_impl(rel_path):
    """Dynamically-loaded HAL implementation libraries, loaded by name at
    runtime (hw_get_module()/HIDL passthrough) rather than linked at
    build time -- declaring them as named PRODUCT_PACKAGES modules risks
    colliding with AOSP's own default module of the same name wherever
    one exists (hardware/libhardware/modules/*, hardware/interfaces/.../
    default). Plain-copy instead. Two conventions, both excluded:
      - HIDL: *@X.Y-impl*.so, anywhere (e.g. camera.device@1.0-impl.so)
      - legacy hw_get_module(): anything under a lib{,64}/hw/ directory
        (e.g. lib/hw/audio.r_submix.default.so)
    """
    basename = rel_path.rsplit("/", 1)[-1]
    if basename.endswith(".so") and "@" in basename and "-impl" in basename:
        return True
    parts = rel_path.split("/")
    return len(parts) >= 3 and parts[0] in ("lib", "lib64") and parts[1] == "hw"

src = "/home/tobim6/AGS2_LOS16/device_huawei_AGS2/proprietary-files.txt"
out_automk = "/home/tobim6/AGS2_LOS16/work/proprietary-files-automk.txt"
out_odm = "/home/tobim6/AGS2_LOS16/work/odm-files.txt"

automk_lines = []
odm_lines = []

with open(src) as f:
    for raw in f:
        line = raw.rstrip("\n")
        stripped = line.strip()
        if not stripped or stripped.startswith("#"):
            continue

        if stripped.startswith("odm/"):
            rel = stripped[len("odm/"):]
            if rel.split("/")[-1] in DROP_BASENAMES:
                continue
            if is_broken_symlink("odm", rel):
                continue
            if is_fake_xml("odm", rel):
                continue
            odm_lines.append(rel)
            continue

        if stripped.startswith("product/"):
            rel_after_product = stripped[len("product/"):]
            if rel_after_product.split("/")[-1] in DROP_BASENAMES:
                continue
            if is_broken_symlink("product", rel_after_product):
                continue
            if needs_build_prebuilt_but_unsupported(rel_after_product):
                continue
            if is_unbuildable_hap(rel_after_product):
                continue
            if is_fake_xml("product", rel_after_product):
                continue
            # TARGET_OUT_PRODUCT_EXECUTABLES isn't a supported install
            # path in this Android version's base_rules.mk -- product
            # partition EXECUTABLES as a module class aren't wired up.
            product_bin = rel_after_product.startswith(("bin/", "sbin/"))
            if (rel_after_product.startswith(CATEGORY_PREFIXES)
                    and not is_hal_impl(rel_after_product)
                    and not product_bin
                    and not is_non_so_lib(rel_after_product)):
                if collides(rel_after_product):
                    if demotable_collision(rel_after_product):
                        automk_lines.append(stripped)
                    continue
                automk_lines.append("-" + stripped)
            else:
                automk_lines.append(stripped)
            continue

        # bare = vendor-sourced
        if stripped.split("/")[-1] in DROP_BASENAMES:
            continue
        if is_broken_symlink("", stripped):
            continue
        if needs_build_prebuilt_but_unsupported(stripped):
            continue
        if is_unbuildable_hap(stripped):
            continue
        if is_fake_xml("", stripped):
            continue
        if (stripped.startswith(CATEGORY_PREFIXES) and not is_hal_impl(stripped)
                and not is_non_so_lib(stripped)):
            if collides(stripped):
                if demotable_collision(stripped):
                    automk_lines.append("vendor/" + stripped)
                continue
            # Leading "-" routes this into PRODUCT_PACKAGES_LIST (proper
            # module handling with multilib/symlink support) rather than
            # a plain PRODUCT_COPY_FILES text copy -- see parse_file_list.
            automk_lines.append("-" + stripped)
        else:
            automk_lines.append("vendor/" + stripped)

# --- Post-process: write_packages derives LOCAL_MODULE from the bare
# basename (minus extension), with no other disambiguation. Two files
# with the same basename at genuinely different paths (not just a
# lib/lib64 32/64-bit arch split of the *same* library) collide. Demote
# every occurrence of such a basename to a plain copy-file instead.
def module_key(path_no_dash):
    """Path with the lib/lib64 arch segment normalized away, so a true
    32/64-bit pair of the same library maps to the same key."""
    parts = path_no_dash.split("/")
    norm = ["lib" if p in ("lib", "lib64") else p for p in parts]
    return "/".join(norm)


def basename_stem(path_no_dash):
    b = path_no_dash.rsplit("/", 1)[-1]
    return b.rsplit(".", 1)[0] if "." in b else b


basename_to_keys = {}
for entry in automk_lines:
    if not entry.startswith("-"):
        continue
    p = entry[1:]
    stem = basename_stem(p)
    basename_to_keys.setdefault(stem, set()).add(module_key(p))

colliding_stems = {stem for stem, keys in basename_to_keys.items() if len(keys) > 1}

final_lines = []
dropped_apk_jar = 0
for entry in automk_lines:
    if entry.startswith("-") and basename_stem(entry[1:]) in colliding_stems:
        p = entry[1:]
        if p.endswith((".apk", ".jar")):
            # Prebuilt .apk/.jar must go through BUILD_PREBUILT (a named
            # module) -- "use BUILD_PREBUILT instead!" is a hard error
            # from build/make/core/Makefile for plain PRODUCT_COPY_FILES.
            # These are all region-specific bundled extras (per-SKU
            # resource overlays for AL00/L03/L09/W09/W19, China-only
            # service apps under region_comm/china/) -- dropped rather
            # than demoted, since we can't give them unique module names
            # without extract_utils support for renaming.
            dropped_apk_jar += 1
            continue
        final_lines.append(p if p.startswith(("vendor/", "product/")) else "vendor/" + p)
    else:
        final_lines.append(entry)

with open(out_automk, "w") as f:
    f.write("\n".join(final_lines) + "\n")
with open(out_odm, "w") as f:
    f.write("\n".join(odm_lines) + "\n")

print(f"automk: {len(final_lines)} lines -> {out_automk} "
      f"({len(colliding_stems)} basenames demoted to copy-files, "
      f"{dropped_apk_jar} apk/jar dropped entirely)")
print(f"odm:    {len(odm_lines)} lines -> {out_odm}")
